// Индекс для поиска: название + описание + раздел + теги.
// Пишем прямо в исходные объекты, чтобы работало и внутри категорий.
window.CALC_CATEGORIES.forEach((cat) => {
  cat.searchText = [cat.name, cat.desc].join(" ").toLowerCase();
  cat.calculators.forEach((c) => {
    c.searchText = [c.name, c.desc || "", cat.name, (c.tags || []).join(" ")].join(" ").toLowerCase();
  });
});

// Плоский список всех калькуляторов — со ссылкой на свою категорию
window.CALC_FLAT = window.CALC_CATEGORIES.reduce((acc, cat) => {
  cat.calculators.forEach((c) => acc.push(Object.assign({}, c, { category: cat })));
  return acc;
}, []);

// Сколько калькуляторов готово (есть url)
window.CALC_COUNT = window.CALC_FLAT.filter((c) => c.url).length;
